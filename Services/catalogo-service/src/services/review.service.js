const db = require('../db');

const PRODUCT_ID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const REVIEW_ID_PATTERN = /^[0-9]{1,18}$/;
const REVIEW_STATUSES = ['PENDING', 'APPROVED', 'REJECTED'];

function httpError(status, message) {
  const error = new Error(message);
  error.status = status;
  return error;
}

async function ensureSchema() {
  await db.query(`
    CREATE TABLE IF NOT EXISTS product_reviews (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      product_id UUID NOT NULL REFERENCES products(id) ON DELETE CASCADE,
      user_id VARCHAR(120) NOT NULL,
      rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
      title VARCHAR(100) NOT NULL,
      comment VARCHAR(1500) NOT NULL,
      status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
      created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
      moderated_at TIMESTAMP WITH TIME ZONE,
      moderated_by VARCHAR(120),
      CONSTRAINT uq_product_reviews_product_user UNIQUE (product_id, user_id)
    )
  `);
  await db.query('CREATE INDEX IF NOT EXISTS idx_product_reviews_public ON product_reviews (product_id, created_at DESC) WHERE status = \'APPROVED\'');
  await db.query('CREATE INDEX IF NOT EXISTS idx_product_reviews_moderation ON product_reviews (status, created_at DESC)');
}

async function getPublicSummaries() {
  const result = await db.query(`
    SELECT product_id AS "productId", ROUND(AVG(rating)::numeric, 1) AS "averageRating", COUNT(*)::int AS "reviewCount"
    FROM product_reviews WHERE status = 'APPROVED' GROUP BY product_id
  `);
  return result.rows.map((row) => ({
    productId: row.productId,
    averageRating: Number(row.averageRating),
    reviewCount: Number(row.reviewCount),
  }));
}

async function getPublicReviews(productId) {
  const product = await db.query('SELECT id FROM products WHERE id = $1 AND is_active = TRUE', [productId]);
  if (!product.rows[0]) return null;
  const result = await db.query(`
    SELECT product_id AS "productId", rating, title, comment, created_at AS "createdAt"
    FROM product_reviews WHERE product_id = $1 AND status = 'APPROVED'
    ORDER BY created_at DESC LIMIT 50
  `, [productId]);
  return result.rows;
}

async function submitReview({ productId, userId, rating, title, comment }) {
  if (!PRODUCT_ID_PATTERN.test(productId)) throw httpError(400, 'El producto no es válido.');
  if (typeof userId !== 'string' || userId.length < 1 || userId.length > 120) throw httpError(401, 'Inicia sesión para dejar tu reseña.');
  if (!Number.isInteger(rating) || rating < 1 || rating > 5) throw httpError(400, 'Selecciona una calificación de 1 a 5 estrellas.');
  if (typeof title !== 'string' || title.trim().length < 3 || title.trim().length > 100) throw httpError(400, 'El título debe tener entre 3 y 100 caracteres.');
  if (typeof comment !== 'string' || comment.trim().length < 10 || comment.trim().length > 1500) throw httpError(400, 'La reseña debe tener entre 10 y 1500 caracteres.');

  const product = await db.query('SELECT id FROM products WHERE id = $1 AND is_active = TRUE', [productId]);
  if (!product.rows[0]) throw httpError(404, 'Este producto no está disponible para reseñas.');

  const result = await db.query(`
    INSERT INTO product_reviews (product_id, user_id, rating, title, comment)
    VALUES ($1, $2, $3, $4, $5)
    ON CONFLICT (product_id, user_id) DO UPDATE
      SET rating = EXCLUDED.rating,
          title = EXCLUDED.title,
          comment = EXCLUDED.comment,
          status = 'PENDING',
          updated_at = CURRENT_TIMESTAMP,
          moderated_at = NULL,
          moderated_by = NULL
    RETURNING id, status, created_at AS "createdAt"
  `, [productId, userId, rating, title.trim(), comment.trim()]);
  return result.rows[0];
}

async function getAdminReviews({ status = 'PENDING', limit = 100, offset = 0 } = {}) {
  if (!['ALL', ...REVIEW_STATUSES].includes(status)) throw httpError(400, 'El filtro de reseñas no es válido.');
  const safeLimit = Math.max(1, Math.min(Number.parseInt(limit, 10) || 100, 100));
  const safeOffset = Math.max(0, Number.parseInt(offset, 10) || 0);
  const values = [];
  let where = '';
  if (status !== 'ALL') { values.push(status); where = `WHERE r.status = $${values.length}`; }
  values.push(safeLimit); const limitIndex = values.length;
  values.push(safeOffset); const offsetIndex = values.length;
  const result = await db.query(`
    SELECT r.id, r.product_id AS "productId", p.name AS "productName", r.user_id AS "reviewerId",
           r.rating, r.title, r.comment, r.status, r.created_at AS "createdAt",
           r.updated_at AS "updatedAt", r.moderated_at AS "moderatedAt", r.moderated_by AS "moderatedBy"
    FROM product_reviews r JOIN products p ON p.id = r.product_id
    ${where}
    ORDER BY CASE WHEN r.status = 'PENDING' THEN 0 ELSE 1 END, r.created_at DESC
    LIMIT $${limitIndex} OFFSET $${offsetIndex}
  `, values);
  return result.rows;
}

async function moderateReview({ reviewId, status, adminUserId }) {
  if (!REVIEW_ID_PATTERN.test(reviewId)) throw httpError(400, 'La reseña indicada no es válida.');
  if (!['APPROVED', 'REJECTED'].includes(status)) throw httpError(400, 'Selecciona aprobar o rechazar la reseña.');
  const result = await db.query(`
    UPDATE product_reviews
    SET status = $1, moderated_at = CURRENT_TIMESTAMP, moderated_by = $2, updated_at = CURRENT_TIMESTAMP
    WHERE id = $3
    RETURNING id, product_id AS "productId", status, rating
  `, [status, String(adminUserId).slice(0, 120), reviewId]);
  return result.rows[0] || null;
}

module.exports = {
  ensureSchema,
  getPublicSummaries,
  getPublicReviews,
  submitReview,
  getAdminReviews,
  moderateReview,
  PRODUCT_ID_PATTERN,
};
